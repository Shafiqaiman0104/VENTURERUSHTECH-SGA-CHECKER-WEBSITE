function csvEscape(value) {
  const str = value === null || value === undefined ? '' : String(value);
  if (/[",\r\n]/.test(str)) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return str;
}

function generateCsvReport(report) {
  const domain = report?.meta?.domain || 'website';
  const scanDate = report?.meta?.scanDate || new Date().toISOString().slice(0, 10);
  const scores = report?.scores || {};
  const summary = report?.summary || {};
  const checks = Array.isArray(report?.checks) ? report.checks : [];

  const lines = [];
  lines.push(['SEO/AEO/GEO Report', domain, scanDate].map(csvEscape).join(','));
  lines.push(['Generated by', 'VentureRush Tech SEO GEO AEO Checker', ''].map(csvEscape).join(','));
  lines.push('');
  lines.push(['Category', 'Score', 'Passed', 'Total'].join(','));
  lines.push(['Overall', scores.overall ?? 0, '', ''].map(csvEscape).join(','));
  lines.push([
    'SEO',
    scores.seo ?? 0,
    summary.seo?.passed ?? 0,
    summary.seo?.total ?? 0,
  ].map(csvEscape).join(','));
  lines.push([
    'AEO',
    scores.aeo ?? 0,
    summary.aeo?.passed ?? 0,
    summary.aeo?.total ?? 0,
  ].map(csvEscape).join(','));
  lines.push([
    'GEO',
    scores.geo ?? 0,
    summary.geo?.passed ?? 0,
    summary.geo?.total ?? 0,
  ].map(csvEscape).join(','));
  lines.push('');
  lines.push(['Check ID', 'Category', 'Status', 'Description'].join(','));

  for (const check of checks) {
    lines.push([
      check.id || '',
      check.pillar || '',
      check.status || '',
      check.description || '',
    ].map(csvEscape).join(','));
  }

  return lines.join('\r\n');
}

module.exports = { generateCsvReport };
